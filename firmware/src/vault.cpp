namespace {

void put_word_u64(uint8_t* w, uint64_t v) {  // 32-byte big-endian word
  std::memset(w, 0, 32);
  for (int i = 0; i < 8; i++) w[31 - i] = uint8_t(v >> (8 * i));
}

void put_word_addr(uint8_t* w, const Addr& a) {
  std::memset(w, 0, 12);
  std::memcpy(w + 12, a.v, 20);
}

Addr table_addr(const char* hex) {
  Addr a;
  addr_from_hex(hex, a);  // compile-time constants (host-tested); never "" here
  return a;
}

}  // namespace

Bytes vault_initialize_calldata(const Addr& owner) {
  // head: owner, offset(string[]) = 0x80, offset(uint256[]) = 0xa0, offset(uint256[]) = 0xc0; tails: three empty
  // arrays (a length word 0 each)
  Bytes out(4 + 7 * 32, 0);
  uint8_t sel[32];
  keccak256(reinterpret_cast<const uint8_t*>(VAULT_INITIALIZE_SIGNATURE), std::strlen(VAULT_INITIALIZE_SIGNATURE), sel);
  std::memcpy(out.data(), sel, 4);
  uint8_t* w = out.data() + 4;
  put_word_addr(w, owner);
  put_word_u64(w + 32, 0x80);
  put_word_u64(w + 64, 0xa0);
  put_word_u64(w + 96, 0xc0);
  // w + 128 .. w + 224: three zero length words (already zero)
  return out;
}

Bytes vault_constructor_args(const Addr& owner) {
  // abi.encode(address, bytes): head = impl, offset 0x40; tail = length, data right-padded to a multiple of 32
  const Bytes init = vault_initialize_calldata(owner);
  const size_t padded = (init.size() + 31) / 32 * 32;
  Bytes out(64 + 32 + padded, 0);
  put_word_addr(out.data(), table_addr(VAULT_IMPLEMENTATION));
  put_word_u64(out.data() + 32, 0x40);
  put_word_u64(out.data() + 64, init.size());
  std::memcpy(out.data() + 96, init.data(), init.size());
  return out;
}

B32 vault_init_code_hash(const Addr& owner) {
  const Bytes args = vault_constructor_args(owner);
  Keccak256 k;
  k.update(VAULT_PROXY_CREATION_CODE, VAULT_PROXY_CREATION_SIZE);
  k.update(args.data(), args.size());
  B32 h;
  k.final(h.v);
  return h;
}

Addr vault_address(const Addr& owner) {
  uint8_t pre[1 + 20 + 32 + 32];
  pre[0] = 0xff;
  std::memcpy(pre + 1, table_addr(VAULT_SIMPLE_FACTORY).v, 20);
  std::memset(pre + 21, 0, 32);  // salt = bytes32(0)
  std::memcpy(pre + 53, vault_init_code_hash(owner).v, 32);
  uint8_t h[32];
  keccak256(pre, sizeof pre, h);
  Addr a;
  std::memcpy(a.v, h + 12, 20);
  return a;
}

